//! Writer for KiCad `.kicad_pcb` files.
//!
//! Written so a board designed here can be opened and checked in KiCad: real
//! footprints with courtyards, silkscreen references, the outline on
//! `Edge.Cuts`, mounting holes and the routed copper as `segment` nodes.
//!
//! The output targets KiCad 10 (file version 20250114). Older KiCad versions
//! will usually open it after an upgrade prompt.

use crate::board::{Board, Footprint};
use crate::router::RoutingResult;
use anyhow::Result;
use std::fmt::Write as _;

/// Board file version understood by KiCad 10.
const KICAD_VERSION: &str = "20250114";

/// Deterministic UUID so repeated exports of the same board are byte-identical.
fn uuid_for(seed: &str, index: usize) -> String {
    // FNV-1a over the seed, expanded into a UUID-shaped string. Uniqueness only
    // has to hold within one file, which this guarantees.
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in seed.as_bytes().iter().chain(index.to_string().as_bytes()) {
        hash ^= *byte as u64;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    let mut hash2: u64 = hash ^ 0x9e37_79b9_7f4a_7c15;
    for i in 0..8 {
        hash2 ^= (hash >> (i * 8)) & 0xff;
        hash2 = hash2.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!(
        "{:08x}-{:04x}-{:04x}-{:04x}-{:012x}",
        (hash >> 32) as u32,
        (hash >> 16) as u16,
        hash as u16,
        (hash2 >> 48) as u16,
        hash2 & 0xffff_ffff_ffff
    )
}

/// Everything the writer needs beyond the bare board.
#[derive(Debug, Clone, Default)]
pub struct FabOptions {
    /// Extra copper-free documentation layers, none by default.
    pub comment: String,
}

/// Write a `.kicad_pcb` for `board` with the copper from `result`.
pub fn write_kicad_pcb(
    board: &Board,
    result: &RoutingResult,
    fab: &FabOptions,
    path: &str,
) -> Result<()> {
    let text = to_kicad_pcb(board, result, fab);
    std::fs::write(path, text)?;
    Ok(())
}

/// Render the board to KiCad text.
pub fn to_kicad_pcb(board: &Board, result: &RoutingResult, _fab: &FabOptions) -> String {
    let mut s = String::with_capacity(64 * 1024);
    let _ = writeln!(
        s,
        "(kicad_pcb (version {KICAD_VERSION}) (generator \"amproute-studio\")"
    );
    let _ = writeln!(s, "  (general (thickness 1.6) (legacy_teardrops no))");
    let _ = writeln!(s, "  (paper \"A4\")");
    let _ = writeln!(s, "  (title_block");
    let _ = writeln!(s, "    (title \"{}\")", escape(&board.name));
    let _ = writeln!(s, "    (rev \"1.0\")");
    let _ = writeln!(
        s,
        "    (comment 1 \"Generated by AmpRoute Studio {} - single-layer LUT preset {}\")",
        crate::VERSION,
        escape(&board.preset.name)
    );
    let _ = writeln!(s, "  )");

    // Layer stack. A single-layer copper board still needs the standard table so
    // KiCad recognises the file.
    let _ = writeln!(s, "  (layers");
    let _ = writeln!(s, "    (0 \"F.Cu\" signal)");
    let _ = writeln!(s, "    (31 \"B.Cu\" signal)");
    let _ = writeln!(s, "    (36 \"B.SilkS\" user \"B.Silkscreen\")");
    let _ = writeln!(s, "    (37 \"F.SilkS\" user \"F.Silkscreen\")");
    let _ = writeln!(s, "    (38 \"B.Mask\" user)");
    let _ = writeln!(s, "    (39 \"F.Mask\" user)");
    let _ = writeln!(s, "    (44 \"Edge.Cuts\" user)");
    let _ = writeln!(s, "    (46 \"B.CrtYd\" user \"B.Courtyard\")");
    let _ = writeln!(s, "    (47 \"F.CrtYd\" user \"F.Courtyard\")");
    let _ = writeln!(s, "    (48 \"B.Fab\" user)");
    let _ = writeln!(s, "    (49 \"F.Fab\" user)");
    let _ = writeln!(s, "  )");

    let _ = writeln!(s, "  (setup");
    let _ = writeln!(s, "    (pad_to_mask_clearance 0)");
    let _ = writeln!(s, "    (allow_soldermask_bridges_in_footprints no)");
    let _ = writeln!(s, "  )");

    // Net table: index 0 is "no net" by convention.
    let _ = writeln!(s, "  (net 0 \"\")");
    for (i, net) in board.nets.iter().enumerate() {
        let _ = writeln!(s, "  (net {} \"{}\")", i + 1, escape(&net.name));
    }

    // Board outline on Edge.Cuts — what KiCad uses for the board shape.
    let _ = writeln!(
        s,
        "  (gr_rect (start 0 0) (end {:.4} {:.4})",
        board.width_mm, board.height_mm
    );
    let _ = writeln!(s, "    (stroke (width 0.1) (type default))");
    let _ = writeln!(s, "    (fill none)");
    let _ = writeln!(s, "    (layer \"Edge.Cuts\")");
    let _ = writeln!(s, "    (uuid \"{}\")", uuid_for("outline", 0));
    let _ = writeln!(s, "  )");

    // Footprints.
    for (fi, fp) in board.footprints.iter().enumerate() {
        write_footprint(&mut s, board, fp, fi);
    }

    // Mounting holes: a non-plated through hole with no net, as KiCad's own
    // `MountingHole` library produces. The reference sits on the fabrication
    // layer: silkscreen text next to a hole overlaps the copper of whatever part
    // the hole happens to be near, which is a DRC warning about nothing.
    for (i, hole) in board.mounting_holes.iter().enumerate() {
        let _ = writeln!(s, "  (footprint \"MountingHole_{:.1}mm\"", hole.drill_mm);
        let _ = writeln!(s, "    (layer \"F.Cu\")");
        let _ = writeln!(s, "    (uuid \"{}\")", uuid_for("hole", i));
        let _ = writeln!(s, "    (at {:.4} {:.4})", hole.x, hole.y);
        let _ = writeln!(
            s,
            "    (property \"Reference\" \"H{}\" (at 0 -3 0) (layer \"F.Fab\") (uuid \"{}\")",
            i + 1,
            uuid_for("hole-ref", i)
        );
        let _ = writeln!(
            s,
            "      (effects (font (size 1 1) (thickness 0.15)))"
        );
        let _ = writeln!(s, "    )");
        let _ = writeln!(
            s,
            "    (property \"Value\" \"MountingHole\" (at 0 3 0) (layer \"F.Fab\") (uuid \"{}\")",
            uuid_for("hole-val", i)
        );
        let _ = writeln!(
            s,
            "      (effects (font (size 1 1) (thickness 0.15)))"
        );
        let _ = writeln!(s, "    )");
        let _ = writeln!(s, "    (attr exclude_from_pos_files exclude_from_bom)");
        // Courtyard around the hole, as the real library footprint has: without
        // it KiCad has no declared keep-out for the part.
        let cr = hole.drill_mm / 2.0 + 0.25;
        let _ = writeln!(
            s,
            "    (fp_circle (center 0 0) (end {:.4} 0)",
            cr
        );
        let _ = writeln!(s, "      (stroke (width 0.05) (type default))");
        let _ = writeln!(s, "      (fill none)");
        let _ = writeln!(s, "      (layer \"F.CrtYd\")");
        let _ = writeln!(s, "      (uuid \"{}\")", uuid_for("hole-crt", i));
        let _ = writeln!(s, "    )");
        let _ = writeln!(
            s,
            "    (pad \"\" np_thru_hole circle (at 0 0) (size {:.4} {:.4}) (drill {:.4}) (layers \"*.Cu\" \"*.Mask\") (uuid \"{}\"))",
            hole.drill_mm + 0.4,
            hole.drill_mm + 0.4,
            hole.drill_mm,
            uuid_for("hole-pad", i)
        );
        let _ = writeln!(s, "  )");
    }

    // Copper.
    for (i, seg) in result.segments.iter().enumerate() {
        let net = board
            .nets
            .iter()
            .position(|n| n.name == seg.net)
            .map(|p| p + 1)
            .unwrap_or(0);
        let _ = writeln!(
            s,
            "  (segment (start {:.4} {:.4}) (end {:.4} {:.4}) (width {:.4}) (layer \"F.Cu\") (net {}) (uuid \"{}\"))",
            seg.x1_mm,
            seg.y1_mm,
            seg.x2_mm,
            seg.y2_mm,
            seg.width_mm,
            net,
            uuid_for("seg", i)
        );
    }

    let _ = writeln!(s, ")");
    s
}

fn write_footprint(s: &mut String, board: &Board, fp: &Footprint, index: usize) {
    // A plain name with no `library:footprint` link, so KiCad does not warn that
    // the part is missing from a library it was never installed into.
    let _ = writeln!(s, "  (footprint \"{}\"", escape(&fp_name(&fp.value)));
    let _ = writeln!(s, "    (layer \"F.Cu\")");
    let _ = writeln!(s, "    (uuid \"{}\")", uuid_for(&fp.refdes, index));
    let _ = writeln!(s, "    (at {:.4} {:.4})", fp.x, fp.y);

    // Reference and value on the fabrication layer. Nothing goes on the
    // silkscreen: this model knows pads and a bounding box, not the artwork of
    // the real part, so a drawn outline would be decoration the DRC rightly
    // rejects where it crosses pads.
    let _ = writeln!(
        s,
        "    (property \"Reference\" \"{}\" (at {:.4} -1.8 0) (layer \"F.Fab\") (uuid \"{}\")",
        escape(&fp.refdes),
        fp.width_mm / 2.0,
        uuid_for(&format!("{}ref", fp.refdes), index)
    );
    let _ = writeln!(s, "      (effects (font (size 1 1) (thickness 0.15)))");
    let _ = writeln!(s, "    )");
    let _ = writeln!(
        s,
        "    (property \"Value\" \"{}\" (at {:.4} {:.4} 0) (layer \"F.Fab\") (uuid \"{}\")",
        escape(&fp.value),
        fp.width_mm / 2.0,
        fp.height_mm + 1.8,
        uuid_for(&format!("{}val", fp.refdes), index)
    );
    let _ = writeln!(s, "      (effects (font (size 1 1) (thickness 0.15)))");
    let _ = writeln!(s, "    )");
    let _ = writeln!(s, "    (attr through_hole)");

    // Courtyard: the pads plus a hair. Drawing the full bounding box instead
    // would claim board area the part does not occupy, and KiCad then reports
    // overlaps with neighbours and with mounting holes that are in fact clear
    // of all copper.
    let (cx0, cy0, cx1, cy1) = pad_bounds(fp);
    let _ = writeln!(
        s,
        "    (fp_rect (start {:.4} {:.4}) (end {:.4} {:.4})",
        cx0, cy0, cx1, cy1
    );
    let _ = writeln!(s, "      (stroke (width 0.05) (type default))");
    let _ = writeln!(s, "      (fill none)");
    let _ = writeln!(s, "      (layer \"F.CrtYd\")");
    let _ = writeln!(s, "      (uuid \"{}\")", uuid_for(&format!("{}crt", fp.refdes), index));
    let _ = writeln!(s, "    )");

    // Pads, each carrying its net so KiCad's DRC and ratsnest work.
    for (pi, pad) in fp.pads.iter().enumerate() {
        let net_index = board
            .nets
            .iter()
            .position(|n| {
                n.nodes
                    .iter()
                    .any(|r| r.refdes == fp.refdes && r.pad == pi)
            })
            .map(|p| p + 1)
            .unwrap_or(0);
        let net_part = if net_index > 0 {
            let name = escape(&board.nets[net_index - 1].name);
            format!(" (net {net_index} \"{name}\")")
        } else {
            " (net 0 \"\")".to_string()
        };
        let _ = writeln!(
            s,
            "    (pad \"{}\" thru_hole circle (at {:.4} {:.4}) (size {:.4} {:.4}) (drill {:.4}) (layers \"*.Cu\" \"*.Mask\"){} (uuid \"{}\"))",
            pi + 1,
            pad.x,
            pad.y,
            pad.size_mm,
            pad.size_mm,
            pad.drill_mm,
            net_part,
            uuid_for(&format!("{}pad{pi}", fp.refdes), index)
        );
    }

    let _ = writeln!(s, "  )");
}

fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Footprint name for the file.
///
/// KiCad reads a bare name as a local footprint. Writing `library:name` instead
/// makes it look the part up in a library that does not exist on this machine
/// and report it as outdated, which is noise rather than a real defect.
fn fp_name(value: &str) -> String {
    value
        .replace([' ', '/', '\\', '"'], "_")
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '-' || *c == '.')
        .collect()
}

/// Bounding box of the pads plus a hair, in footprint-relative coordinates.
///
/// The courtyard has to describe the area the part actually claims. The full
/// `width_mm × height_mm` box is only a drawing aid; using it as a courtyard
/// makes neighbouring parts that never touch copper look like they collide.
fn pad_bounds(fp: &Footprint) -> (f64, f64, f64, f64) {
    if fp.pads.is_empty() {
        return (0.0, 0.0, fp.width_mm, fp.height_mm);
    }
    let mut x0 = f64::MAX;
    let mut y0 = f64::MAX;
    let mut x1 = f64::MIN;
    let mut y1 = f64::MIN;
    for pad in &fp.pads {
        let r = pad.size_mm / 2.0;
        x0 = x0.min(pad.x - r);
        y0 = y0.min(pad.y - r);
        x1 = x1.max(pad.x + r);
        y1 = y1.max(pad.y + r);
    }
    // 0.25 mm clearance band: the standard courtyard excess.
    (x0 - 0.25, y0 - 0.25, x1 + 0.25, y1 + 0.25)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::board::{Footprint, LutPreset, Net, NetClass, Pad, PadRef};
    use crate::sexpr::parse;

    fn simple_board() -> Board {
        let mut b = Board::new("Test board", 60.0, 40.0, LutPreset::reliable());
        let mut fp1 = Footprint::new("R1", "10k", NetClass::Signal, 10.0, 15.0, 8.0, 5.0);
        fp1.pads = vec![Pad::new(1.5, 2.5, 2.0, 1.0), Pad::new(6.5, 2.5, 2.0, 1.0)];
        let mut fp2 = Footprint::new("R2", "10k", NetClass::Signal, 40.0, 15.0, 8.0, 5.0);
        fp2.pads = vec![Pad::new(1.5, 2.5, 2.0, 1.0), Pad::new(6.5, 2.5, 2.0, 1.0)];
        b.add_footprint(fp1);
        b.add_footprint(fp2);
        b.add_net(Net::new(
            "N1",
            NetClass::Signal,
            vec![PadRef::new("R1", 0), PadRef::new("R2", 0)],
        ));
        b
    }

    fn routed(board: &Board) -> RoutingResult {
        crate::router::Router::new(0.5, board.width_mm, board.height_mm).route_board(board)
    }

    #[test]
    fn output_is_a_parseable_kicad_board() {
        let board = simple_board();
        let result = routed(&board);
        let text = to_kicad_pcb(&board, &result, &FabOptions::default());
        let root = parse(&text).expect("must parse as S-expression");
        assert_eq!(root.kind(), Some("kicad_pcb"));
        assert!(!root.children("footprint").collect::<Vec<_>>().is_empty());
    }

    #[test]
    fn outline_reaches_the_declared_board_size() {
        let board = simple_board();
        let text = to_kicad_pcb(&board, &RoutingResult::new(), &FabOptions::default());
        assert!(text.contains("(end 60.0000 40.0000)"), "outline: {text}");
        assert!(text.contains("Edge.Cuts"));
    }

    #[test]
    fn pads_carry_their_net_so_kicad_can_check_connectivity() {
        let board = simple_board();
        let text = to_kicad_pcb(&board, &RoutingResult::new(), &FabOptions::default());
        assert!(text.contains("(net 1 \"N1\")"), "net table missing");
        // Pads on the net must reference it, otherwise KiCad reports them as
        // unconnected and the whole point of exporting is lost.
        let net_pad_count = text.matches("(net 1 \"N1\")").count();
        assert!(
            net_pad_count >= 3,
            "expected the net table entry plus two pads, found {net_pad_count}"
        );
    }

    #[test]
    fn copper_segments_are_emitted_with_widths() {
        let board = simple_board();
        let result = routed(&board);
        let text = to_kicad_pcb(&board, &result, &FabOptions::default());
        assert!(text.contains("(segment (start"), "no copper written");
        assert!(text.contains("(layer \"F.Cu\")"));
    }

    #[test]
    fn mounting_holes_are_written_as_npth() {
        let mut board = simple_board();
        board.add_corner_holes(4.0, 3.2);
        let text = to_kicad_pcb(&board, &RoutingResult::new(), &FabOptions::default());
        assert!(text.contains("np_thru_hole"));
        assert!(text.contains("(drill 3.2000)"));
        assert!(text.contains("exclude_from_bom"));
        assert_eq!(text.matches("np_thru_hole").count(), 4);
    }

    #[test]
    fn uuids_are_deterministic_and_distinct() {
        let a = uuid_for("seg", 1);
        let b = uuid_for("seg", 1);
        let c = uuid_for("seg", 2);
        assert_eq!(a, b, "same seed must produce the same uuid");
        assert_ne!(a, c, "different index must produce a different uuid");
        assert_eq!(a.len(), 36);
    }

    #[test]
    fn quotes_in_names_are_escaped() {
        let mut board = simple_board();
        board.name = "Bob \"The\" Amp".into();
        let text = to_kicad_pcb(&board, &RoutingResult::new(), &FabOptions::default());
        assert!(text.contains(r#"Bob \"The\" Amp"#));
        assert!(parse(&text).is_ok(), "escaping must keep the file parseable");
    }
}
